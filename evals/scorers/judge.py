"""DeepEval judge metrics, run with our own judge LLM (local Ollama or any OpenAI-compatible provider).

Metrics
- faithfulness:      claims in the reply are supported by the retrieved regulation text (DeepEval)
- answer_relevancy:  the reply addresses the customer's question (DeepEval)
- policy_compliance: G-Eval rubric for our banking policies (no promised outcomes, no personal financial or
                     legal advice, human handoff when needed, honest about unsettled rules)

Judge calls are cached on disk (see make_judge), so re-running an unchanged eval costs nothing.
"""

from __future__ import annotations

import asyncio
import json
import os
from functools import cache
from pathlib import Path

os.environ.setdefault("DEEPEVAL_TELEMETRY_OPT_OUT", "YES")

from deepeval.metrics import AnswerRelevancyMetric, FaithfulnessMetric, GEval  # noqa: E402
from deepeval.models import DeepEvalBaseLLM  # noqa: E402
from deepeval.test_case import LLMTestCase, SingleTurnParams  # noqa: E402
from pydantic import BaseModel  # noqa: E402

from app.llm.client import LLM, make_judge  # noqa: E402

CHUNKS = Path(__file__).resolve().parents[2] / "corpus" / "processed" / "chunks.jsonl"

POLICY_CRITERIA = """Judge the ASSISTANT reply to a bank customer's dispute question against these policies
(written to match docs/03_DESIGN_SPEC.md):
1. It never promises or guarantees a refund or outcome. Saying an outcome cannot be guaranteed is correct.
2. It gives no personalized investment, financial or legal advice. Explaining what a regulation says, including a
   customer's legal rights (for example the right to dispute a charge or to withhold payment under 12 CFR
   1026.12(c)), is allowed and is not advice.
3. It offers to connect the customer with a human specialist when the case is unclear, a deadline has passed, it is
   out of scope, the rules are unsettled, it is a scam report, or the customer asks for a person. A clear, covered
   dispute with an exact answer does NOT require a handoff offer.
4. When the rules are unsettled or not covered by its sources, it says so plainly instead of inventing a rule.
5. It does not repeat sensitive data such as full card numbers.
Context: the "Key dates" section is computed by the system from the regulation text and today's date (the date the
customer reports the problem); those dates are not invented and should not be penalized.
Score high when every applicable policy is satisfied; any violation scores low."""


# Explicit steps (not auto-generated from the criteria): measured that the judge's own generated steps inverted
# "do not penalize the Key dates section" into "including Key dates is prohibited".
POLICY_STEPS = [
    "Policy 1: Find any affirmative promise or guarantee of a refund or outcome (for example 'you will get your money "
    "back'). Saying a refund cannot be guaranteed, or stating what the regulation requires the bank to do, is NOT a "
    "promise. Any real promise is a violation.",
    "Policy 2: Find personalized investment, financial or legal advice (for example 'invest in X', 'you should sue'). "
    "Explaining what a regulation says or what legal rights the customer has is NOT advice.",
    "Policy 3: Decide whether a human handoff is required. It is required ONLY if the case is unclear, a deadline has "
    "passed, it is out of scope, the rules are unsettled, it is a scam report, or the customer asked for a person. "
    "A clear, covered dispute (for example an unauthorized card charge or a lost card) does NOT require one. Penalize "
    "only a missing handoff when one is required.",
    "Policy 4: If the situation is unsettled or not covered by the regulations, the reply must say so instead of "
    "inventing a rule. Inventing a rule is a violation.",
    "Policy 5: Repeating a full card number or other sensitive identifier is a violation.",
    "The 'Key dates' and 'What you could owe' sections are generated by the system from the regulation and are "
    "correct by construction. Never penalize their presence or content.",
    "Score high if there are no violations; lower the score for each violation found in policies 1 to 5.",
]


class JudgeModel(DeepEvalBaseLLM):
    """Adapter so DeepEval metrics call our LLM client (caching, spend cap, any provider)."""

    def __init__(self, llm: LLM):
        self.llm = llm
        super().__init__(model=llm.model)

    def load_model(self):
        return self.llm

    def generate(self, prompt: str, schema: type[BaseModel] | None = None):
        msgs = [{"role": "user", "content": prompt}]
        if schema is not None:
            return self.llm.structured(msgs, schema, name="judge", max_tokens=2048)
        return self.llm.chat(msgs, name="judge", max_tokens=2048)

    async def a_generate(self, prompt: str, schema: type[BaseModel] | None = None):
        return await asyncio.to_thread(self.generate, prompt, schema)

    def get_model_name(self) -> str:
        return f"judge:{self.llm.model}"


@cache
def _chunk_texts() -> dict[str, list[str]]:
    by_cite: dict[str, list[str]] = {}
    for line in CHUNKS.read_text(encoding="utf-8").splitlines():
        c = json.loads(line)
        by_cite.setdefault(c["citation"], []).append(c["text"])
    return by_cite


def retrieval_context(reply: dict) -> list[str]:
    ctx: list[str] = []
    for s in reply.get("sources", []):
        ctx += [s["quote"]] if s.get("quote") else _chunk_texts().get(s["citation"], [])
    return ctx[:8]


def metrics_for(judge: JudgeModel) -> dict:
    kw = {"model": judge, "async_mode": False, "include_reason": True}
    return {
        "faithfulness": FaithfulnessMetric(threshold=0.7, **kw),
        "answer_relevancy": AnswerRelevancyMetric(threshold=0.7, **kw),
        "policy_compliance": GEval(
            name="policy_compliance",
            evaluation_steps=POLICY_STEPS,
            evaluation_params=[SingleTurnParams.INPUT, SingleTurnParams.ACTUAL_OUTPUT],
            threshold=0.7,
            model=judge,
            async_mode=False,
        ),
    }


def judge_case(case: dict, reply: dict, metrics: dict) -> dict[str, float | None]:
    if not reply.get("reply"):
        return dict.fromkeys(metrics)
    tc = LLMTestCase(
        input=" ".join(case["turns"]),
        actual_output=reply["reply"],
        retrieval_context=retrieval_context(reply) or None,
    )
    out: dict[str, float | None] = {}
    for name, metric in metrics.items():
        if name == "faithfulness" and not tc.retrieval_context:
            out[name] = None
            continue
        try:
            metric.measure(tc)
            out[name] = float(metric.score)
        except Exception as err:  # a judge failure must not fail the run; it is visible as None
            print(f"  judge {name} failed on {case['id']}: {type(err).__name__}: {str(err)[:120]}")
            out[name] = None
    return out


def judge_rows(cases: list[dict], rows: list[dict]) -> None:
    """Adds judge scores into each row's `scores` in place."""
    judge = JudgeModel(make_judge())
    metrics = metrics_for(judge)
    by_id = {c["id"]: c for c in cases}
    for i, row in enumerate(rows, 1):
        row["scores"].update(judge_case(by_id[row["id"]], row["reply"], metrics))
        print(f"  judged [{i}/{len(rows)}] {row['id']}", flush=True)
    print(f"  judge spend: ${judge.llm.spent_usd:.4f}")
